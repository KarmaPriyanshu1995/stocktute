import type { CurriculumLevel, CurriculumLesson, CurriculumModule, LessonStatus } from "./types";

function lesson(
  slug: string,
  title: string,
  summaryOrStatus: string,
  status: LessonStatus = "published",
  minutes = 7,
): CurriculumLesson {
  if (summaryOrStatus === "published" || summaryOrStatus === "locked") {
    return {
      slug,
      title,
      minutes,
      status: summaryOrStatus,
      summary: `${title} is on this level’s syllabus and unlocks with the level.`,
    };
  }
  return { slug, title, minutes, summary: summaryOrStatus, status };
}

function mod(id: string, title: string, lessons: CurriculumLesson[]): CurriculumModule {
  return { id, title, lessons };
}

