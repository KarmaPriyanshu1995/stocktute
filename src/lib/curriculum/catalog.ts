export const ALL_LESSONS: CurriculumLesson[] = LEVELS.flatMap((level) =>
  level.modules.flatMap((m) => m.lessons),
);

export function getLevel(id: number): CurriculumLevel | undefined {
  return LEVELS.find((l) => l.id === id);
}

export function findLesson(
  slug: string,
): { lesson: CurriculumLesson; module: CurriculumModule; level: CurriculumLevel } | undefined {
  for (const level of LEVELS) {
    for (const module of level.modules) {
      const lesson = module.lessons.find((item) => item.slug === slug);
      if (lesson) return { lesson, module, level };
    }
  }
  return undefined;
}

export function nextPublishedLesson(slug: string): CurriculumLesson | undefined {
  const published = ALL_LESSONS.filter((l) => l.status === "published");
  const index = published.findIndex((l) => l.slug === slug);
  if (index < 0) return undefined;
  return published[index + 1];
}

export function courseStats() {
  return {
    levels: LEVELS.length,
    lessons: ALL_LESSONS.length,
    published: ALL_LESSONS.filter((l) => l.status === "published").length,
  };
}
